#!/usr/bin/env node
// scripts/gen-pronoun-gender.mjs — which pronouns say "a person" and which say "a thing", per language, from Universal Dependencies.  (2026-10-14)
//   node scripts/gen-pronoun-gender.mjs [--ud /Users/mlacy/Documents/data/ud]   -> fold-chat-pronoun-gender.js (GENERATED, committed)
//
// Replaces the hand-typed CASTS.pronounGender ({ he him his she her hers: "p", it its: "n" }) of fold-chat-casts.js.
//
// THE RULE (a pure function of treebank counts, `deriveGender`, tested on synthetic counts in fold-chat-pronoun-gender.test.mjs):
//   1. A language has NATURAL gender when no determiner and no adjective of its treebank carries a Gender feature (nothing agrees with a noun's
//      gender). There a pronoun's Gender is its REFERENT's: Masc/Fem = a person, Neut = a thing. In a language with GRAMMATICAL gender (es, fr, de,
//      pt, ca, it, pl, ar, he, hi …) "él"/"il"/"er" stand for a table as well as a man, so the language contributes NOTHING: no animacy filter, as before.
//   2. Within a natural-gender language a FORM counts when PRON is its dominant use over all its occurrences, it is a personal (PronType=Prs),
//      third-person, non-reflexive pronoun, and the majority of its gendered uses agree: Masc|Fem -> "p", Neut -> "n". Forms are alphabetic, and
//      attested at least twice (a hapax is a typo).
// Nothing is listed by hand.
import fs from "node:fs"; import path from "node:path";

/** deriveGender(stats) -> { natural, forms: { form: "p"|"n" } }.  stats = { agree: { det, detG, adj, adjG }, forms: { form: { n, up, f:{ "Feat=Val": count } } } } */
export function deriveGender(stats) {
  const { agree, forms } = stats;
  const natural = agree.detG + agree.adjG === 0;
  const out = {};
  if (!natural) return { natural, forms: out };
  for (const [w, f] of Object.entries(forms)) {
    if (!/^\p{L}+$/u.test(w) || f.n < 2) continue;
    if ((f.up.PRON || 0) * 2 <= f.n) continue;                                    // PRON must be the form's dominant use over ALL occurrences
    const prs = f.prsPerson3 || 0; if (prs * 2 <= (f.up.PRON || 0)) continue;     // personal, third person, on the majority of its PRON uses
    if (f.reflex) continue;                                                       // himself/herself/itself: a different class (reflexive)
    const p = f.masc + f.fem, n = f.neut;
    if (p + n === 0) continue;
    if (p > n) out[w] = "p"; else if (n > p) out[w] = "n";
  }
  return { natural, forms: out };
}

/** One pass over a train file -> the counts deriveGender reads. */
export function statsOf(file) {
  const forms = Object.create(null); const agree = { det: 0, detG: 0, adj: 0, adjG: 0 };
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (!line || line[0] === "#") continue; const c = line.split("\t"); if (c.length < 8) continue;
    if (/^\d+-\d+$/.test(c[0])) { const w0 = c[1].toLocaleLowerCase(); (forms[w0] ||= { n: 0, up: {}, masc: 0, fem: 0, neut: 0, prsPerson3: 0, reflex: 0 }).n++; continue; }   // a multiword surface is an occurrence that is not the pronoun
    if (/[.]/.test(c[0])) continue;
    const w = c[1].toLocaleLowerCase(), up = c[3], ft = c[5];
    if (up === "DET") { agree.det++; if (/(^|\|)Gender=/.test(ft)) agree.detG++; }
    if (up === "ADJ") { agree.adj++; if (/(^|\|)Gender=/.test(ft)) agree.adjG++; }
    const f = (forms[w] ||= { n: 0, up: {}, masc: 0, fem: 0, neut: 0, prsPerson3: 0, reflex: 0 });
    f.n++; f.up[up] = (f.up[up] || 0) + 1;
    if (up === "PRON") {
      if (/PronType=Prs/.test(ft) && /Person=3/.test(ft)) f.prsPerson3++;
      if (/Reflex=Yes/.test(ft)) f.reflex++;
      if (/Gender=Masc/.test(ft)) f.masc++; else if (/Gender=Fem/.test(ft)) f.fem++; else if (/Gender=Neut/.test(ft)) f.neut++;
    }
  }
  return { agree, forms };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2); const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
  const UD = opt("--ud", "/Users/mlacy/Documents/data/ud"), OUT = new URL("../fold-chat-pronoun-gender.js", import.meta.url);
  const res = {}, seen = new Set(), grammatical = [];
  for (const dir of fs.readdirSync(UD).sort()) {
    const p = path.join(UD, dir); if (!fs.statSync(p).isDirectory()) continue; const train = fs.readdirSync(p).find((f) => /train\.conllu$/.test(f)); if (!train) continue;
    const lang = dir.split("_")[0]; if (seen.has(lang)) continue; seen.add(lang);
    const r = deriveGender(statsOf(path.join(p, train)));
    if (!r.natural) { grammatical.push(lang); continue; }
    const forms = Object.fromEntries(Object.entries(r.forms).sort(([a], [b]) => (a < b ? -1 : 1)));
    if (Object.keys(forms).length) res[lang] = { treebank: dir, forms };
  }
  const body = `// fold-chat-pronoun-gender.js — GENERATED by scripts/gen-pronoun-gender.mjs from Universal Dependencies treebanks. Do not edit by hand.
// lang -> { form: "p" (a person) | "n" (a thing) } for the languages whose treebank shows NATURAL gender (no determiner or adjective agrees in Gender).
// A language with grammatical gender is absent on purpose: its pronouns say nothing about animacy.
export const PRONOUN_GENDER = Object.freeze(${JSON.stringify(res, null, 1)});
`;
  fs.writeFileSync(OUT, body);
  console.log(`natural-gender languages with gendered pronouns: ${Object.keys(res).join(" ")} · grammatical (no table): ${grammatical.length} · en: ${Object.entries(res.en?.forms || {}).map(([k, v]) => k + ":" + v).join(" ")}`);
}
