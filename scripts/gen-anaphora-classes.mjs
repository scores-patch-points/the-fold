// Today one class: `wh`, the question/relative words (fold-chat-anaphora.js uses it to see that a connective opens a clause of its own:
// "and who painted the Mona Lisa"). Its rule, `deriveWh`:
//   a form is a wh word of its language when its dominant UPOS is pronominal or adverbial (PRON, ADV, DET, ADJ) and the MAJORITY of its occurrences
//   carry PronType=Int or PronType=Rel; attested at least twice; alphabetic.
// English derives from en_ewt; es and fr are emitted for the record but NOT wired (their treebanks hold few questions: "cómo", "cuándo", "quand",
// "que" fall below the rule), so those two keep their declared lists. See docs/NO-FIXED-LISTS.md.
import fs from "node:fs"; import path from "node:path";

const WH_UPOS = new Set(["PRON", "ADV", "DET", "ADJ"]);
/** deriveWh(stats) -> [forms].  stats.forms[form] = { n, up: {UPOS: count}, intRel: tokens whose PronType contains Int or Rel } */
export function deriveWh(stats) {
  const out = [];
  for (const [w, f] of Object.entries(stats.forms)) {
    if (!/^\p{L}+$/u.test(w) || f.n < 2) continue;
    let dom = null, m = -1; for (const [u, c] of Object.entries(f.up)) if (c > m) { m = c; dom = u; }
    if (!WH_UPOS.has(dom)) continue;
    if (f.intRel * 2 > f.n) out.push(w);
  }
  return out.sort();
}

export function statsOf(file) {
  const forms = Object.create(null);
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (!line || line[0] === "#") continue; const c = line.split("\t"); if (c.length < 8) continue;
    if (/^\d+-\d+$/.test(c[0])) { (forms[c[1].toLocaleLowerCase()] ||= { n: 0, up: {}, intRel: 0 }).n++; continue; }
    if (/[.]/.test(c[0])) continue;
    const f = (forms[c[1].toLocaleLowerCase()] ||= { n: 0, up: {}, intRel: 0 });
    f.n++; f.up[c[3]] = (f.up[c[3]] || 0) + 1;
    const m = /(?:^|\|)PronType=([^|]+)/.exec(c[5]); if (m && m[1].split(",").some((v) => v === "Int" || v === "Rel")) f.intRel++;
  }
  return { forms };
}

