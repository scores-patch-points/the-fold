#!/usr/bin/env node
// scripts/gen-pronoun-classes.mjs — personal pronouns that can point back, per language, from Universal Dependencies.  (2026-10-14)
//   node scripts/gen-pronoun-classes.mjs [--ud /Users/mlacy/Documents/data/ud]   -> fold-chat-pronouns.js (GENERATED, committed)
// A form is a STRONG anaphor of its language when PRON is its dominant use over ALL its occurrences and, among its PRON uses, the MAJORITY are personal (PronType=Prs),
// third person, not reflexive and not an expletive subject (deprel expl*). Nothing is listed by hand; the unit is the treebank's own
// annotation, so a language gets a class exactly when a treebank exists, with no declared overlay. Forms keep their accents:
// Spanish "él" (pronoun) is not "el" (article).
import fs from "node:fs"; import path from "node:path";
const args = process.argv.slice(2); const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const UD = opt("--ud", "/Users/mlacy/Documents/data/ud"), OUT = new URL("../fold-chat-pronouns.js", import.meta.url);
const res = {};
for (const dir of fs.readdirSync(UD).sort()) {
  const p = path.join(UD, dir); if (!fs.statSync(p).isDirectory()) continue; const train = fs.readdirSync(p).find((f) => /train\.conllu$/.test(f)); if (!train) continue;
  const lang = dir.split("_")[0]; if (res[lang]) continue;
  const by = new Map(), tot = new Map(); let n = 0;
  for (const line of fs.readFileSync(path.join(p, train), "utf8").split("\n")) {
    if (!line || line[0] === "#") continue; const c = line.split("\t"); if (c.length < 8) continue;
    // a multiword-token line ("no" = em+o, "del" = de+el, "zum") is an occurrence of that surface form that is NOT a pronoun: it counts toward the form's total
    if (/^\d+-\d+$/.test(c[0])) { const w0 = c[1].toLocaleLowerCase(); tot.set(w0, (tot.get(w0) ?? 0) + 1); continue; }
    if (/[.]/.test(c[0])) continue; n++;
    const w = c[1].toLocaleLowerCase(); tot.set(w, (tot.get(w) ?? 0) + 1);
    if (c[3] !== "PRON") continue; const m = by.get(w) ?? { pron: 0, pt: 0 };
    m.pron++; if (/PronType=Prs/.test(c[5]) && /Person=3/.test(c[5]) && !/Reflex=Yes/.test(c[5]) && !/^expl/.test(c[7])) m.pt++;
    by.set(w, m);
  }
  // PRON must be the form's dominant use among ALL its occurrences (an article that is sometimes tagged PRON is not a pronoun), and the
  // personal 3rd-person reading must be the majority of its PRON uses
  const strong = [...by].filter(([w, m]) => m.pron * 2 > tot.get(w) && m.pt * 2 > m.pron).map(([w]) => w).sort();
  if (strong.length) res[lang] = { treebank: dir, tokens: n, strong };
}
const body = `// fold-chat-pronouns.js — GENERATED by scripts/gen-pronoun-classes.mjs from Universal Dependencies treebanks. Do not edit by hand.
// lang -> the personal, 3rd-person, non-reflexive, non-expletive pronouns (majority of the form's PRON uses) that can point back to a being.
export const PRONOUNS = Object.freeze(${JSON.stringify(res, null, 1)});
`;
fs.writeFileSync(OUT, body);
console.log(`${Object.keys(res).length} languages · ${(body.length / 1024).toFixed(0)} KB · es: ${res.es?.strong.join(" ")} · de: ${res.de?.strong.join(" ")} · pt: ${res.pt?.strong.join(" ")}`);
